"""Results-document generation.

``docs/RESULTS.md`` is written by this module, not by hand. Every number in it
comes from the evaluation that just ran, and regenerating it is one command. That
is the only arrangement under which a results table stays true: a hand-maintained
one is correct on the day it is written and quietly wrong from the first refactor
onward.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any

from pharos.config import REPO_ROOT, PharosConfig
from pharos.eval.metrics import format_ci
from pharos.eval.run import HEADLINE_METRICS, LOWER_IS_BETTER, SuiteResult

METRIC_LABELS: dict[str, str] = {
    "ndcg@10": "nDCG@10",
    "recall@10": "Recall@10",
    "recall@5": "Recall@5",
    "mrr": "MRR",
    "valence_skew": "VSD ↓",
    "rating_error": "CRE ↓",
    "stratum_coverage": "Coverage",
    "distinct_reviews": "Distinct reviews",
}


def _table(header: list[str], rows: list[list[str]], align_first_left: bool = True) -> str:
    sep = ["---" if i == 0 and align_first_left else "---:" for i in range(len(header))]
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def write_results_markdown(
    results: list[SuiteResult],
    deltas: dict[str, dict[str, tuple[float, float, float, float]]],
    fidelity: dict[str, Any],
    corpus_meta: dict[str, Any],
    index_info: dict[str, Any],
    cfg: PharosConfig,
    n_goldset: int,
    size_bands: list[dict[str, Any]] | None = None,
    path: Path | None = None,
) -> Path:
    """Render the results document. Returns the path written."""
    path = path or (REPO_ROOT / "docs" / "RESULTS.md")
    path.parent.mkdir(parents=True, exist_ok=True)

    lookup = {r.name: r for r in results}
    full = lookup.get("full")

    parts: list[str] = []
    parts.append("# Results\n")
    parts.append(
        "> Generated by `pharos evaluate`. Every number below is recomputed from the\n"
        "> shipped code on each run; nothing here is transcribed by hand.\n"
    )
    parts.append(
        f"**Generated** {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())} · "
        f"**config fingerprint** `{cfg.fingerprint()}` · "
        f"**encoder** `{index_info.get('encoder')}` · "
        f"**gold set** {n_goldset} queries\n"
    )

    # ----------------------------------------------------------------- #
    parts.append("## 1. Corpus\n")
    parts.append(
        _table(
            ["property", "value"],
            [
                ["Source reviews", f"{corpus_meta.get('rows_in', 0):,}"],
                ["After cleaning", f"{corpus_meta.get('rows_out', 0):,}"],
                ["Sampled for this build", f"{corpus_meta.get('reviews_after_subsample', 0):,}"],
                ["Evidence units", f"{corpus_meta.get('evidence_units', 0):,}"],
                ["Units per review", f"{corpus_meta.get('units_per_review', 0)}"],
                ["Distinct drugs", f"{corpus_meta.get('distinct_drugs', 0):,}"],
                ["Distinct conditions", f"{corpus_meta.get('distinct_conditions', 0):,}"],
                ["Index dimension", f"{index_info.get('embedding_dim', 0)}"],
                ["BM25 vocabulary", f"{index_info.get('bm25_vocabulary', 0):,}"],
            ],
        )
    )

    parts.append("\n### 1.1 Data defects found and repaired\n")
    parts.append(
        "Counts are over the full 215,063-review corpus, before subsampling. "
        "Reproduce with `pharos audit-labels`.\n"
    )
    parts.append(
        _table(
            ["defect", "rows affected", "handling"],
            [
                [
                    "HTML entities in review text",
                    f"{corpus_meta.get('entities_unescaped', 0):,}",
                    "decoded to a fixed point",
                ],
                [
                    "Export quote wrapping",
                    f"{corpus_meta.get('quote_unwrapped', 0):,}",
                    "unwrapped",
                ],
                [
                    "Condition label — trailing deletion",
                    f"{corpus_meta.get('condition_repaired_trailing', 0):,}",
                    "repaired from the documented table",
                ],
                [
                    "Condition label — leading deletion",
                    f"{corpus_meta.get('condition_repaired_leading', 0):,}",
                    "repaired from the documented table",
                ],
                [
                    "Condition field held the review footer",
                    f"{corpus_meta.get('condition_artifact', 0):,}",
                    "set to null, row retained",
                ],
                [
                    "Condition field held a truncated drug name",
                    f"{corpus_meta.get('condition_unrepairable', 0):,}",
                    "set to null rather than guessed",
                ],
                [
                    "Missing condition",
                    f"{corpus_meta.get('condition_missing', 0):,}",
                    "dropped",
                ],
                [
                    "Exact duplicates (drug, text)",
                    f"{corpus_meta.get('exact_duplicates', 0):,}",
                    "first occurrence kept",
                ],
                [
                    "Near duplicates (MinHash ≥ 0.92)",
                    f"{corpus_meta.get('near_duplicates', 0):,}",
                    "first occurrence kept",
                ],
                [
                    "Volunteered identifiers",
                    f"{corpus_meta.get('deidentified_rows', 0):,}",
                    "replaced with typed placeholders",
                ],
            ],
        )
    )

    # ----------------------------------------------------------------- #
    parts.append("\n## 2. The problem being measured\n")
    shares = fidelity.get("corpus_stratum_shares", {})
    parts.append(
        f"The corpus is sharply bimodal. **{fidelity.get('share_extreme', 0) * 100:.1f}%** of "
        f"reviews sit at the extremes (1–2 or 9–10), the corpus mean rating is "
        f"**{fidelity.get('corpus_mean_rating', 0):.2f}/10**, and the outcome shares are "
        + ", ".join(f"**{k} {v * 100:.1f}%**" for k, v in shares.items())
        + ". A retriever that ranks by similarity alone inherits and amplifies that "
        "shape, because emphatic reviews are also the ones most lexically similar to "
        "an emphatic question.\n"
    )
    parts.append(
        "Two metrics quantify the resulting distortion, both defined in "
        "`pharos/retrieval/stratified.py`:\n\n"
        "- **VSD** (Valence Skew Divergence) — Jensen–Shannon divergence, in bits, "
        "between the retrieved panel's outcome distribution and the cohort's true one. "
        "0 is a perfectly representative panel.\n"
        "- **CRE** (Cohort Rating Error) — absolute difference between the panel's mean "
        "rating and the cohort's, on the 1–10 scale. How many stars a reader of the "
        "panel alone would be misled by.\n"
    )

    # ----------------------------------------------------------------- #
    parts.append("\n## 3. Ablation study\n")
    parts.append(
        f"All configurations share one index and one gold set of {n_goldset} queries. "
        "Each row changes exactly one mechanism. Brackets are 95% bootstrap "
        f"intervals over {cfg.eval.bootstrap_n} resamples. ↓ marks metrics where lower "
        "is better.\n"
    )
    header = ["configuration"] + [METRIC_LABELS.get(m, m) for m in HEADLINE_METRICS]
    rows = []
    for result in results:
        cells = [f"`{result.name}`"]
        for metric in HEADLINE_METRICS:
            if metric in result.metrics:
                mean, lo, hi = result.metrics[metric]
                cell = format_ci(mean, lo, hi)
                if result.name == "full":
                    cell = f"**{cell}**"
                cells.append(cell)
            else:
                cells.append("—")
        rows.append(cells)
    parts.append(_table(header, rows))

    parts.append("\n### 3.1 What each configuration changes\n")
    parts.append(
        _table(
            ["configuration", "change"],
            [[f"`{r.name}`", r.description] for r in results],
        )
    )

    # ----------------------------------------------------------------- #
    if deltas and full is not None:
        parts.append("\n### 3.2 Paired deltas against the full system\n")
        parts.append(
            "Paired bootstrap on per-query differences, which is the right test here: "
            "the same queries run through every configuration, and query-to-query "
            "variance is far larger than the effects being measured. A negative delta "
            "on an ↑ metric means the ablated configuration is worse. Intervals "
            "excluding zero are marked.\n"
        )
        for metric in HEADLINE_METRICS:
            rows = []
            for name, metric_deltas in deltas.items():
                if metric not in metric_deltas:
                    continue
                delta, lo, hi, p = metric_deltas[metric]
                significant = (lo > 0) or (hi < 0)
                direction = ""
                if significant:
                    better = (delta > 0) != (metric in LOWER_IS_BETTER)
                    direction = " ✓ better" if better else " ✗ worse"
                rows.append(
                    [
                        f"`{name}`",
                        f"{delta:+.4f}",
                        f"[{lo:+.4f}, {hi:+.4f}]",
                        f"{p:.3f}",
                        ("**significant**" + direction) if significant else "n.s.",
                    ]
                )
            if rows:
                parts.append(f"\n**{METRIC_LABELS.get(metric, metric)}**\n")
                parts.append(_table(["configuration", "Δ vs full", "95% CI", "p", "verdict"], rows))

    # ----------------------------------------------------------------- #
    if size_bands:
        parts.append("\n### 3.3 Where the distortion lives\n")
        parts.append(
            "The same metrics, split by how many reviews the queried cohort contains, "
            "for the full system against `naive-baseline`. The gap widens with cohort "
            "size: the more units similarity search has to choose from, the more freedom "
            "it has to choose unrepresentatively.\n"
        )
        parts.append(
            _table(
                [
                    "cohort size",
                    "queries",
                    "VSD full ↓",
                    "VSD baseline ↓",
                    "reduction",
                    "CRE full ↓",
                    "CRE baseline ↓",
                    "coverage full",
                    "coverage baseline",
                ],
                [
                    [
                        band["band"],
                        str(band["n_queries"]),
                        f"{band['full_vsd']:.4f}",
                        f"{band['baseline_vsd']:.4f}",
                        f"{band['vsd_reduction'] * 100:.0f}%",
                        f"{band['full_cre']:.3f}",
                        f"{band['baseline_cre']:.3f}",
                        f"{band['full_coverage']:.3f}",
                        f"{band['baseline_coverage']:.3f}",
                    ]
                    for band in size_bands
                ],
            )
        )

    parts.append("\n## 4. Reading these numbers\n")
    if full is not None and "naive-baseline" in lookup:
        base = lookup["naive-baseline"]
        full_vsd = full.metrics.get("valence_skew", (0, 0, 0))[0]
        base_vsd = base.metrics.get("valence_skew", (0, 0, 0))[0]
        full_cre = full.metrics.get("rating_error", (0, 0, 0))[0]
        base_cre = base.metrics.get("rating_error", (0, 0, 0))[0]
        full_ndcg = full.metrics.get("ndcg@10", (0, 0, 0))[0]
        base_ndcg = base.metrics.get("ndcg@10", (0, 0, 0))[0]
        reduction = (1 - full_vsd / base_vsd) * 100 if base_vsd else 0.0
        parts.append(
            f"Against `naive-baseline` -- dense top-k with no fusion, no redundancy "
            f"control and no stratification, which is what a conventional RAG "
            f"retriever does -- the full system reduces valence skew from "
            f"**{base_vsd:.4f}** to **{full_vsd:.4f}** — a **{reduction:.0f}%** reduction — "
            f"and cohort rating error from **{base_cre:.3f}** to **{full_cre:.3f}** stars, "
            f"while nDCG@10 moves from {base_ndcg:.4f} to {full_ndcg:.4f}.\n"
        )
        parts.append(
            "That trade is the finding. Representativeness is not free: reserving panel "
            "slots for minority outcomes means admitting units that rank slightly lower "
            "on relevance. The claim this project makes is that the trade is worth taking "
            "for a summarisation task, because a panel that misrepresents its cohort "
            "produces a confidently wrong answer, and a panel with marginally lower nDCG "
            "produces a slightly less on-topic one. Those failures are not equivalent, "
            "and only one of them is visible to the reader.\n"
        )
    parts.append(
        "\n**What is not claimed.** The gold set derives relevance from corpus metadata "
        "(`pharos/eval/goldset.py`), so it measures whether retrieval finds units matching "
        "a query's structured intent — a necessary condition for good retrieval, not a "
        "sufficient one. Aspect labels come from a deterministic weak labeller and carry "
        "its error rate. Nothing here measures answer quality as a clinician would judge "
        "it, and no statistic computed over self-selected reviews is a pharmacovigilance "
        "signal.\n"
    )

    parts.append("\n## 5. Reproducing\n")
    parts.append(
        "```bash\n"
        "pharos fetch-data\n"
        "pharos build-corpus\n"
        "pharos build-index\n"
        "pharos evaluate      # regenerates this file\n"
        "```\n\n"
        "No API key and no model download are required for any of the above: the default "
        "encoder is fitted on the corpus itself, and every metric in this document is "
        "computed without a generative model.\n"
    )

    path.write_text("\n".join(parts))
    return path
